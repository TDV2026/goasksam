// Refreshes lib/data/disposableDomains.js from the maintained public list (disposable-email-domains project,
// github.com/disposable-email-domains/disposable-email-domains, CC0 public domain). Run, review the diff, commit.
//   node scripts/updateDisposableDomains.mjs
import fs from "node:fs";
const SRC = "https://raw.githubusercontent.com/disposable-email-domains/disposable-email-domains/main/disposable_email_blocklist.conf";
const r = await fetch(SRC); if (!r.ok) { console.error("fetch failed", r.status); process.exit(1); }
const list = [...new Set((await r.text()).split(/\r?\n/).map(s => s.trim().toLowerCase()).filter(s => s && !s.startsWith("#") && /^[a-z0-9.-]+\.[a-z]{2,}$/.test(s)))].sort();
const out = `// Throwaway (disposable) email domains, refused at sign-up (lib/_signup.js). GENERATED by
// scripts/updateDisposableDomains.mjs from the disposable-email-domains project (CC0 public domain), ${new Date().toISOString().slice(0, 10)}.
// ${list.length} domains. Do not edit by hand: rerun the script.
export const DISPOSABLE_DOMAINS = ${JSON.stringify(list.join("\n"))};
`;
fs.writeFileSync(new URL("../lib/data/disposableDomains.js", import.meta.url), out);
console.log("wrote", list.length, "domains");
